"""Small synthetic end-to-end demonstration against the running API."""

import json
import os
import time
from pathlib import Path

import httpx


def main():
    key = os.environ.get("MEMORY_CLIENT_API_KEY")
    if not key:
        raise SystemExit("Set MEMORY_CLIENT_API_KEY to the OWNER token generated by init")
    base = os.environ.get("MEMORY_API_URL", "http://127.0.0.1:8080")
    fixture = Path(__file__).resolve().parents[1] / "examples/conversations.jsonl"
    ids = set()
    with httpx.Client(
        base_url=base, headers={"Authorization": f"Bearer {key}"}, timeout=120
    ) as client:

        def call(method, path, **args):
            response = client.request(method, path, **args)
            response.raise_for_status()
            return response.json()

        for line in fixture.read_text(encoding="utf-8").splitlines():
            result = call("POST", "/v1/episodes", json=json.loads(line))
            ids.add(result["episode_id"])
        deadline = time.monotonic() + 90
        while time.monotonic() < deadline:
            jobs = call("GET", "/v1/jobs")["jobs"]
            selected = [j for j in jobs if j["episode_id"] in ids]
            if any(j["status"] == "failed" for j in selected):
                raise SystemExit("Demo extraction failed; inspect /v1/jobs")
            if len(selected) == len(ids) and all(j["status"] == "done" for j in selected):
                break
            time.sleep(0.2)
        else:
            raise SystemExit("Demo still processing; inspect /v1/jobs")
        graph = call("GET", "/v1/map")
        # Auto-review ONLY synthetic demo-only nodes. Never confirm mixed/private evidence.
        for node in graph["nodes"]:
            if node["evidence"] and all(e["episode_id"] in ids for e in node["evidence"]):
                call("POST", f"/v1/nodes/{node['id']}/review", json={"status": "confirmed"})
        for edge in graph["edges"]:
            if edge["evidence"] and all(e["episode_id"] in ids for e in edge["evidence"]):
                call("POST", f"/v1/links/{edge['id']}/review", json={"status": "confirmed"})
        report = call("POST", "/v1/maintenance/consolidate")
        context = call("POST", "/v1/context", json={"query": "Lidská kontrola", "max_chars": 8000})
        print(
            json.dumps(
                {
                    "demo_episodes": len(ids),
                    "map_summary": report,
                    "context_items": len(context["items"]),
                    "used_chars": context["used_chars"],
                },
                ensure_ascii=False,
                indent=2,
            )
        )
        print(context["text"])


if __name__ == "__main__":
    main()
